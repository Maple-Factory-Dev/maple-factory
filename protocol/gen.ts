// Writes the protocol types for Rust (runner), TypeScript (server, web), Swift (Mac, iOS) and Kotlin (Android).
// node protocol/gen.ts            write them
// node protocol/gen.ts --check    exit 1 if any is out of date

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { enums, structs, unions, version, type Fields, type Variant } from "./schema.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const header = (comment: string) => `${comment} Generated by protocol/gen.ts from protocol/schema.ts. Do not edit.\n`;

type Ty =
  | { kind: "prim"; name: string }
  | { kind: "ref"; name: string }
  | { kind: "opt"; of: Ty }
  | { kind: "list"; of: Ty }
  | { kind: "map"; of: Ty };

const prims = new Set(["string", "bool", "u16", "u32", "u64", "i32", "f64", "uuid", "json"]);

function parse(src: string): Ty {
  if (src.endsWith("?")) return { kind: "opt", of: parse(src.slice(0, -1)) };
  if (src.endsWith("[]")) return { kind: "list", of: parse(src.slice(0, -2)) };
  const map = /^map<(.+)>$/.exec(src);
  if (map) return { kind: "map", of: parse(map[1]) };
  if (prims.has(src)) return { kind: "prim", name: src };
  if (src in structs || src in enums) return { kind: "ref", name: src };
  throw new Error(`unknown type ${src}`);
}

// Field names that are keywords in one of the languages; the generator refuses them rather than escaping.
const reserved = new Set([
  "type", "ref", "self", "protocol", "default", "case", "in", "is", "fn", "impl", "mod", "move", "match", "where", "enum", "struct", "let", "var", "func", "extension", "import", "public", "static",
  "val", "fun", "object", "when", "as", "class", "interface", "this", "super", "null", "true", "false", "throw", "return", "try", "typealias", "typeof", "package", "while", "for", "if", "else", "do", "break", "continue",
]);
const allFields = [
  ...Object.entries(structs).map(([n, s]) => [n, s.fields] as const),
  ...Object.entries(unions).flatMap(([n, u]) => Object.entries(u.variants).map(([t, v]) => [`${n}.${t}`, v.fields ?? {}] as const)),
];
for (const [owner, fields] of allFields) {
  for (const name of Object.keys(fields)) if (reserved.has(name)) throw new Error(`${owner}.${name}: "${name}" is a keyword in Rust, Swift or Kotlin; pick another name`);
}

const pascal = (tag: string) => tag.split(/[._-]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const snake = (name: string) => name.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
const usesJSON = [...Object.values(structs).map((s) => s.fields), ...Object.values(unions).flatMap((u) => Object.values(u.variants).map((v) => v.fields ?? {}))]
  .some((f) => Object.values(f).some((t) => t.replace(/[?\[\]]/g, "") === "json"));

// MARK: Rust

function rustType(t: Ty): string {
  switch (t.kind) {
    case "prim":
      return { string: "String", bool: "bool", u16: "u16", u32: "u32", u64: "u64", i32: "i32", f64: "f64", uuid: "Uuid", json: "serde_json::Value" }[t.name]!;
    case "ref": return t.name;
    case "opt": return `Option<${rustType(t.of)}>`;
    case "list": return `Vec<${rustType(t.of)}>`;
    case "map": return `BTreeMap<String, ${rustType(t.of)}>`;
  }
}

const rustDoc = (doc: string | undefined, indent = "") => (doc ? doc.split("\n").map((l) => `${indent}/// ${l}\n`).join("") : "");

function rustFields(fields: Fields, docs: Record<string, string> = {}, indent = "    ") {
  return Object.entries(fields).map(([name, src]) => {
    const t = parse(src);
    const attrs: string[] = [];
    if (t.kind === "opt") attrs.push(`#[serde(default, skip_serializing_if = "Option::is_none")]`);
    if (t.kind === "list") attrs.push(`#[serde(default)]`);
    if (t.kind === "map") attrs.push(`#[serde(default)]`);
    return rustDoc(docs[name], indent) + attrs.map((a) => `${indent}${a}\n`).join("") + `${indent}pub ${snake(name)}: ${rustType(t)},\n`;
  }).join("");
}

function rust(): string {
  let out = header("//!") + "\n#![allow(dead_code)]\n\nuse serde::{Deserialize, Serialize};\n#[allow(unused_imports)]\nuse std::collections::BTreeMap;\nuse uuid::Uuid;\n\n";
  out += `pub const PROTOCOL_VERSION: u32 = ${version};\n\n`;
  for (const [name, e] of Object.entries(enums)) {
    out += rustDoc(e.doc) + `#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = "camelCase")]\npub enum ${name} {\n`;
    // A value this build doesn't know (a newer server added it) decodes as the catch-all instead of failing the message.
    // An enum with its own `unknown` value uses that; the rest get `Other`.
    for (const [value, doc] of Object.entries(e.values)) out += rustDoc(doc, "    ") + (value === "unknown" ? "    #[serde(other)]\n" : "") + `    ${pascal(value)},\n`;
    if (!("unknown" in e.values)) out += `    /// A value this build doesn't know yet; newer servers may send them.\n    #[serde(other)]\n    Other,\n`;
    out += "}\n\n";
  }
  for (const [name, s] of Object.entries(structs)) {
    out += rustDoc(s.doc) + `#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(rename_all = "camelCase")]\npub struct ${name} {\n${rustFields(s.fields, s.fieldDocs)}}\n\n`;
  }
  for (const [name, u] of Object.entries(unions)) {
    out += rustDoc(u.doc) + `#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(tag = "type", rename_all_fields = "camelCase")]\npub enum ${name} {\n`;
    for (const [tag, v] of Object.entries(u.variants)) {
      out += rustDoc(v.doc, "    ") + `    #[serde(rename = "${tag}")]\n`;
      const fields = v.fields ?? {};
      out += Object.keys(fields).length
        ? `    ${pascal(tag)} {\n${rustFields(fields, v.fieldDocs, "        ").replaceAll("pub ", "")}    },\n`
        : `    ${pascal(tag)},\n`;
    }
    out += "}\n\n";
  }
  return out.trimEnd() + "\n";
}

// MARK: TypeScript

function tsType(t: Ty): string {
  switch (t.kind) {
    case "prim": return { string: "string", bool: "boolean", uuid: "string", json: "unknown" }[t.name as "string"] ?? "number";
    case "ref": return t.name;
    case "opt": return `${tsType(t.of)} | null`;
    case "list": return `${tsType(t.of)}[]`;
    case "map": return `Record<string, ${tsType(t.of)}>`;
  }
}

const tsDoc = (doc: string | undefined, indent = "") => (doc ? `${indent}/** ${doc} */\n` : "");

function tsFields(fields: Fields, docs: Record<string, string> = {}, indent = "  ") {
  return Object.entries(fields).map(([name, src]) => {
    const t = parse(src);
    return tsDoc(docs[name], indent) + `${indent}${name}${t.kind === "opt" ? "?" : ""}: ${tsType(t)};\n`;
  }).join("");
}

function ts(): string {
  let out = header("//") + `\nexport const PROTOCOL_VERSION = ${version};\n\n`;
  for (const [name, e] of Object.entries(enums)) {
    out += tsDoc(e.doc) + `export type ${name} = ${Object.keys(e.values).map((v) => JSON.stringify(v)).join(" | ")};\n`;
    out += `export const ${name}Values: readonly ${name}[] = ${JSON.stringify(Object.keys(e.values))};\n\n`;
  }
  for (const [name, s] of Object.entries(structs)) out += tsDoc(s.doc) + `export interface ${name} {\n${tsFields(s.fields, s.fieldDocs)}}\n\n`;
  for (const [name, u] of Object.entries(unions)) {
    const members: string[] = [];
    for (const [tag, v] of Object.entries(u.variants)) {
      const typeName = `${name}_${pascal(tag)}`;
      members.push(typeName);
      out += tsDoc(v.doc) + `export interface ${typeName} {\n  type: ${JSON.stringify(tag)};\n${tsFields(v.fields ?? {}, v.fieldDocs)}}\n\n`;
    }
    out += tsDoc(u.doc) + `export type ${name} = ${members.join(" | ")};\n`;
    out += `export const ${name}Types = ${JSON.stringify(Object.keys(u.variants))} as const;\n\n`;
  }
  return out.trimEnd() + "\n";
}

// MARK: Swift

function swiftType(t: Ty): string {
  switch (t.kind) {
    case "prim":
      return { string: "String", bool: "Bool", u16: "UInt16", u32: "UInt32", u64: "UInt64", i32: "Int32", f64: "Double", uuid: "String", json: "JSONValue" }[t.name]!;
    case "ref": return t.name;
    case "opt": return `${swiftType(t.of)}?`;
    case "list": return `[${swiftType(t.of)}]`;
    case "map": return `[String: ${swiftType(t.of)}]`;
  }
}

const swiftDoc = (doc: string | undefined, indent = "") => (doc ? `${indent}/// ${doc}\n` : "");
const swiftName = (name: string) => (["default", "protocol", "self", "case", "in", "is"].includes(name) ? `\`${name}\`` : name);

function swiftStruct(name: string, fields: Fields, docs: Record<string, string> = {}, doc?: string): string {
  const entries = Object.entries(fields);
  let out = swiftDoc(doc) + `public struct ${name}: Codable, Hashable, Sendable {\n`;
  for (const [field, src] of entries) out += swiftDoc(docs[field], "    ") + `    public var ${swiftName(field)}: ${swiftType(parse(src))}\n`;
  const params = entries.map(([field, src]) => {
    const t = parse(src);
    const fallback = t.kind === "opt" ? " = nil" : t.kind === "list" ? " = []" : t.kind === "map" ? " = [:]" : "";
    return `${field}: ${swiftType(t)}${fallback}`;
  });
  out += `\n    public init(${params.join(", ")}) {\n${entries.map(([f]) => `        self.${f} = ${swiftName(f)}\n`).join("")}    }\n`;
  // Lists and maps may be left out on the wire (serde's `default`), so decode them leniently.
  if (entries.some(([, src]) => /\[\]$|^map</.test(src))) {
    out += `\n    public init(from decoder: Decoder) throws {\n        let c = try decoder.container(keyedBy: CodingKeys.self)\n`;
    for (const [field, src] of entries) {
      const t = parse(src);
      const ty = swiftType(t);
      if (t.kind === "opt") out += `        ${field} = try c.decodeIfPresent(${swiftType(t.of)}.self, forKey: .${field})\n`;
      else if (t.kind === "list") out += `        ${field} = try c.decodeIfPresent(${ty}.self, forKey: .${field}) ?? []\n`;
      else if (t.kind === "map") out += `        ${field} = try c.decodeIfPresent(${ty}.self, forKey: .${field}) ?? [:]\n`;
      else out += `        ${field} = try c.decode(${ty}.self, forKey: .${field})\n`;
    }
    out += `    }\n`;
  }
  return out + "}\n\n";
}

function swift(): string {
  let out = header("//") + `\nimport Foundation\n\npublic static let protocolVersion: UInt32 = ${version}\n\n`;
  if (usesJSON) {
    out += `/// Any JSON value, for fields the protocol passes through untouched.
public enum JSONValue: Codable, Hashable, Sendable {
    case null, bool(Bool), number(Double), string(String), array([JSONValue]), object([String: JSONValue])

    public init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if c.decodeNil() { self = .null }
        else if let v = try? c.decode(Bool.self) { self = .bool(v) }
        else if let v = try? c.decode(Double.self) { self = .number(v) }
        else if let v = try? c.decode(String.self) { self = .string(v) }
        else if let v = try? c.decode([JSONValue].self) { self = .array(v) }
        else { self = .object(try c.decode([String: JSONValue].self)) }
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .null: try c.encodeNil()
        case .bool(let v): try c.encode(v)
        case .number(let v): try c.encode(v)
        case .string(let v): try c.encode(v)
        case .array(let v): try c.encode(v)
        case .object(let v): try c.encode(v)
        }
    }
}

`;
  }
  for (const [name, e] of Object.entries(enums)) {
    // Tolerant of values a newer server adds: they decode as `.other("…")` rather than failing the whole message.
    const values = Object.keys(e.values);
    if (values.includes("other")) throw new Error(`${name}.other: "other" is the generated catch-all; pick another name`);
    out += swiftDoc(e.doc) + `public enum ${name}: Codable, Hashable, Sendable, CaseIterable, RawRepresentable {\n`;
    for (const [value, doc] of Object.entries(e.values)) out += swiftDoc(doc, "    ") + `    case ${swiftName(value)}\n`;
    out += `    /// A value this build doesn't know yet; newer servers may send them.\n    case other(String)\n\n`;
    out += `    /// The values this build knows; never \`.other\`.\n    public static let allCases: [${name}] = [${values.map((v) => `.${swiftName(v)}`).join(", ")}]\n\n`;
    out += `    public init(rawValue: String) {\n        switch rawValue {\n${values.map((v) => `        case "${v}": self = .${swiftName(v)}\n`).join("")}        default: self = .other(rawValue)\n        }\n    }\n\n`;
    out += `    public var rawValue: String {\n        switch self {\n${values.map((v) => `        case .${swiftName(v)}: "${v}"\n`).join("")}        case .other(let value): value\n        }\n    }\n\n`;
    out += `    public init(from decoder: Decoder) throws {\n        self.init(rawValue: try decoder.singleValueContainer().decode(String.self))\n    }\n\n`;
    out += `    public func encode(to encoder: Encoder) throws {\n        var c = encoder.singleValueContainer()\n        try c.encode(rawValue)\n    }\n\n`;
    out += `    public static func == (a: ${name}, b: ${name}) -> Bool { a.rawValue == b.rawValue }\n    public func hash(into hasher: inout Hasher) { hasher.combine(rawValue) }\n`;
    out += "}\n\n";
  }
  for (const [name, s] of Object.entries(structs)) out += swiftStruct(name, s.fields, s.fieldDocs, s.doc);
  for (const [name, u] of Object.entries(unions)) {
    const variants = Object.entries(u.variants);
    for (const [tag, v] of variants) if (v.fields && Object.keys(v.fields).length) out += swiftStruct(`${name}${pascal(tag)}`, v.fields, v.fieldDocs, v.doc);
    const caseName = (tag: string) => { const p = pascal(tag); return swiftName(p[0].toLowerCase() + p.slice(1)); };
    const hasFields = (v: { fields?: Fields }) => !!v.fields && Object.keys(v.fields).length > 0;
    out += swiftDoc(u.doc) + `public enum ${name}: Codable, Hashable, Sendable {\n`;
    for (const [tag, v] of variants) out += `    case ${caseName(tag)}${hasFields(v) ? `(${name}${pascal(tag)})` : ""}\n`;
    out += `    /// A message this build doesn't know yet; newer servers and runners may send them.\n    case unknown(String)\n\n`;
    out += `    private enum TypeKey: String, CodingKey { case type }\n\n`;
    out += `    public init(from decoder: Decoder) throws {\n        let type = try decoder.container(keyedBy: TypeKey.self).decode(String.self, forKey: .type)\n        switch type {\n`;
    for (const [tag, v] of variants) out += `        case "${tag}": self = .${caseName(tag)}${hasFields(v) ? `(try ${name}${pascal(tag)}(from: decoder))` : ""}\n`;
    out += `        default: self = .unknown(type)\n        }\n    }\n\n`;
    out += `    public func encode(to encoder: Encoder) throws {\n        var c = encoder.container(keyedBy: TypeKey.self)\n        switch self {\n`;
    for (const [tag, v] of variants) {
      out += hasFields(v)
        ? `        case .${caseName(tag)}(let body):\n            try c.encode("${tag}", forKey: .type)\n            try body.encode(to: encoder)\n`
        : `        case .${caseName(tag)}:\n            try c.encode("${tag}", forKey: .type)\n`;
    }
    out += `        case .unknown(let type):\n            try c.encode(type, forKey: .type)\n        }\n    }\n}\n\n`;
  }
  // Namespaced so the app's own model types (Machine, Member…) don't collide: `Wire.Machine`.
  const [preamble, body] = out.split("public static let protocolVersion");
  const indented = ("public static let protocolVersion" + body).trimEnd().split("\n").map((l) => (l ? "    " + l : l)).join("\n");
  return `${preamble}public enum Wire {\n${indented}\n}\n`;
}

// MARK: Kotlin

function kotlinType(t: Ty, qualify = false): string {
  switch (t.kind) {
    case "prim":
      return { string: "String", bool: "Boolean", u16: "Int", u32: "Long", u64: "Long", i32: "Int", f64: "Double", uuid: "String", json: "JsonElement" }[t.name]!;
    // A union's variants are nested classes, so a ref inside one names the package to skip a variant of the same name.
    case "ref": return qualify ? `dev.maplefactory.wire.${t.name}` : t.name;
    case "opt": return `${kotlinType(t.of, qualify)}?`;
    case "list": return `List<${kotlinType(t.of, qualify)}>`;
    case "map": return `Map<String, ${kotlinType(t.of, qualify)}>`;
  }
}

const kotlinDoc = (doc: string | undefined, indent = "") => (doc ? `${indent}/** ${doc.replaceAll("\n", " ")} */\n` : "");

function kotlinClass(name: string, fields: Fields, docs: Record<string, string> = {}, doc: string | undefined, indent: string, parent?: string): string {
  const entries = Object.entries(fields);
  const params = entries.map(([field, src]) => {
    const t = parse(src);
    // Optional fields, lists and maps may be left out on the wire (serde's `default`).
    const fallback = t.kind === "opt" ? " = null" : t.kind === "list" ? " = emptyList()" : t.kind === "map" ? " = emptyMap()" : "";
    return kotlinDoc(docs[field], indent + "    ") + `${indent}    val ${field}: ${kotlinType(t, !!parent)}${fallback},\n`;
  });
  return kotlinDoc(doc, indent) + `${indent}@Serializable\n${indent}data class ${name}(\n${params.join("")}${indent})${parent ? ` : ${parent}()` : ""}\n`;
}

function kotlin(): string {
  let out = header("//") + `
@file:Suppress("unused")
@file:OptIn(ExperimentalSerializationApi::class)

package dev.maplefactory.wire

import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.KSerializer
import kotlinx.serialization.Serializable
import kotlinx.serialization.descriptors.PrimitiveKind
import kotlinx.serialization.descriptors.PrimitiveSerialDescriptor
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.descriptors.buildClassSerialDescriptor
import kotlinx.serialization.encoding.Decoder
import kotlinx.serialization.encoding.Encoder
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonDecoder
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonEncoder
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

const val PROTOCOL_VERSION: Int = ${version}

/** How the factory's JSON reads and writes: unknown keys skipped, nulls left out, lists and maps always sent. */
val WireJson: Json = Json {
    ignoreUnknownKeys = true
    explicitNulls = false
    encodeDefaults = true
    coerceInputValues = true
}

/** An enum as its JSON string; a value this build doesn't know decodes as \`unknown\` instead of failing the message. */
open class WireEnumSerializer<T : Enum<T>>(name: String, private val values: List<T>, private val raw: (T) -> String, private val unknown: T) : KSerializer<T> {
    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("dev.maplefactory.wire.$name", PrimitiveKind.STRING)
    override fun serialize(encoder: Encoder, value: T) = encoder.encodeString(raw(value))
    override fun deserialize(decoder: Decoder): T {
        val value = decoder.decodeString()
        return values.firstOrNull { it != unknown && raw(it) == value } ?: unknown
    }
}

/** A union keyed on its \`type\` field; a type this build doesn't know decodes as \`unknown(type)\`. */
abstract class WireUnionSerializer<T : Any>(name: String) : KSerializer<T> {
    override val descriptor: SerialDescriptor = buildClassSerialDescriptor("dev.maplefactory.wire.$name")
    protected abstract fun decode(json: Json, type: String, body: JsonObject): T
    protected abstract fun encode(json: Json, value: T): Pair<String, JsonElement?>

    override fun deserialize(decoder: Decoder): T {
        val input = decoder as JsonDecoder
        val body = input.decodeJsonElement().jsonObject
        val type = body["type"]?.jsonPrimitive?.contentOrNull ?: ""
        return decode(input.json, type, JsonObject(body - "type"))
    }

    override fun serialize(encoder: Encoder, value: T) {
        val output = encoder as JsonEncoder
        val (type, body) = encode(output.json, value)
        output.encodeJsonElement(JsonObject(mapOf("type" to JsonPrimitive(type)) + (body?.jsonObject ?: emptyMap())))
    }
}

`;
  for (const [name, e] of Object.entries(enums)) {
    const values = Object.keys(e.values);
    out += kotlinDoc(e.doc) + `@Serializable(with = ${name}.Serializer::class)\nenum class ${name}(val raw: String) {\n`;
    for (const [value, doc] of Object.entries(e.values)) out += kotlinDoc(doc, "    ") + `    ${pascal(value)}("${value}"),\n`;
    // An enum with its own `unknown` value uses that; the rest get one.
    if (!values.includes("unknown")) out += `    /** A value this build doesn't know yet; newer servers may send them. */\n    Unknown("unknown"),\n`;
    out += `    ;\n\n    object Serializer : WireEnumSerializer<${name}>("${name}", entries, { it.raw }, Unknown)\n}\n\n`;
  }
  for (const [name, s] of Object.entries(structs)) out += kotlinClass(name, s.fields, s.fieldDocs, s.doc, "") + "\n";
  for (const [name, u] of Object.entries(unions)) {
    const variants = Object.entries(u.variants);
    const hasFields = (v: Variant) => !!v.fields && Object.keys(v.fields).length > 0;
    out += kotlinDoc(u.doc) + `@Serializable(with = ${name}.Serializer::class)\nsealed class ${name} {\n`;
    for (const [tag, v] of variants) {
      out += hasFields(v) ? kotlinClass(pascal(tag), v.fields!, v.fieldDocs, v.doc, "    ", name) : kotlinDoc(v.doc, "    ") + `    data object ${pascal(tag)} : ${name}()\n`;
    }
    out += `    /** A message this build doesn't know yet; newer servers and runners may send them. */\n    data class Unknown(val type: String) : ${name}()\n\n`;
    out += `    object Serializer : WireUnionSerializer<${name}>("${name}") {\n`;
    out += `        override fun decode(json: Json, type: String, body: JsonObject): ${name} = when (type) {\n`;
    for (const [tag, v] of variants) out += `            "${tag}" -> ${hasFields(v) ? `json.decodeFromJsonElement(${pascal(tag)}.serializer(), body)` : pascal(tag)}\n`;
    out += `            else -> Unknown(type)\n        }\n\n`;
    out += `        override fun encode(json: Json, value: ${name}): Pair<String, JsonElement?> = when (value) {\n`;
    for (const [tag, v] of variants) out += `            is ${pascal(tag)} -> "${tag}" to ${hasFields(v) ? `json.encodeToJsonElement(${pascal(tag)}.serializer(), value)` : "null"}\n`;
    out += `            is Unknown -> value.type to null\n        }\n    }\n}\n\n`;
  }
  return out.trimEnd() + "\n";
}

