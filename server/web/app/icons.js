/**
 * The Lucide icon `name` as an inline <svg>, `size` px square (default 16), stroked in currentColor.
 * It's decorative (aria-hidden) unless `label` is given, which makes it an image with that name.
 * An unknown name throws, so a typo shows up the first time the page draws it.
 */
export function icon(name, { size = 16, label, class: cls } = {}) {
  const shapes = LUCIDE[name];
  if (!shapes) throw new Error(`No Lucide icon "${name}" in icons.js`);
  const svg = document.createElementNS(SVG, "svg");
  const attrs = {
    class: cls ? `icon icon-${name} ${cls}` : `icon icon-${name}`,
    width: size, height: size, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor",
    "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round",
  };
  if (label) Object.assign(attrs, { role: "img", "aria-label": label });
  else attrs["aria-hidden"] = "true";
  for (const [k, v] of Object.entries(attrs)) svg.setAttribute(k, String(v));
  for (const [tag, shapeAttrs] of shapes) {
    const el = document.createElementNS(SVG, tag);
    for (const [k, v] of Object.entries(shapeAttrs)) el.setAttribute(k, v);
    svg.append(el);
  }
  return svg;
}

/** Fills every [data-icon] slot under `root` with its icon, once (a slot that already has one is left alone). */
export function fillIcons(root = document) {
  for (const slot of root.querySelectorAll("[data-icon]")) {
    if (slot.querySelector("svg")) continue;
    slot.append(icon(slot.dataset.icon, { size: Number(slot.dataset.iconSize) || undefined }));
  }
}
