#!/usr/bin/env node
// Bundles the docs editor (server/docs-editor, TipTap + Yjs) into one checked-in ES module that /app loads
// without a build step: server/web/app/docs/editor.bundle.js, plus editor.css (MF-361, docs/planning-docs.md).
// `--check` builds in memory and fails if the checked-in files differ (part of `npm run gen:check`).
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "server/docs-editor/src");
const OUT = join(root, "server/web/app/docs");
// The Mac app bundles a copy of the embed for its signed-out demo doc (MF-362), served from its own scheme.
const MAC = join(root, "apps/mac/Sources/MapleFactory/Resources/DocsEmbed");
// The phone apps bundle it too, for their demo docs (MF-370): iOS as a folder resource, Android as app assets.
const IOS = join(root, "apps/ios/Resources/DocsEmbed");
const ANDROID = join(root, "apps/android/app/src/main/assets/docs");
const check = process.argv.includes("--check");

// The source hash covers the editor's sources, the task resolver it imports from /app, and the lockfile
// (so a dependency bump shows up as a stale bundle too).
const inputs = [...readdirSync(SRC).sort().map((f) => join(SRC, f)), join(root, "server/web/app/markdown.js"), join(root, "package-lock.json")];
const hash = createHash("sha256");
for (const f of inputs) hash.update(relative(root, f)).update("\0").update(readFileSync(f));
const sourceHash = hash.digest("hex").slice(0, 16);

const version = (name) => JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8")).version;
const versions = ["@tiptap/core", "yjs", "y-websocket", "prosemirror-markdown", "esbuild"].map((n) => `${n}@${version(n)}`).join(" ");
const banner = `// GENERATED by scripts/build-docs-editor.mjs from server/docs-editor (source ${sourceHash}). Do not edit; run \`npm run build:docs\`.\n// ${versions}`;

const result = await build({
  entryPoints: [join(SRC, "editor.js")],
  bundle: true,
  format: "esm",
  minify: true,
  target: "es2022",
  platform: "browser",
  legalComments: "none",
  write: false,
  banner: { js: banner },
  logLevel: "warning",
});
const files = {
  "editor.bundle.js": result.outputFiles[0].text,
  "editor.css": `/* GENERATED from server/docs-editor/src/editor.css by scripts/build-docs-editor.mjs. Do not edit. */\n${readFileSync(join(SRC, "editor.css"), "utf8")}`,
};

const targets = Object.entries(files).map(([name, text]) => [join(OUT, name), text]);
for (const name of ["embed.html", "editor.bundle.js", "editor.css"]) {
  const text = name === "embed.html" ? readFileSync(join(OUT, name), "utf8") : files[name];
  for (const dir of [MAC, IOS, ANDROID]) targets.push([join(dir, name), text]);
}

let stale = 0;
for (const [to, text] of targets) {
  const same = existsSync(to) && readFileSync(to, "utf8") === text;
  if (check) {
    console.log(`${relative(root, to)}  ${same ? "ok" : "STALE"}`);
    if (!same) stale++;
  } else {
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, text);
    console.log(`${relative(root, to)}  ${(text.length / 1024).toFixed(0)} KB${same ? " (unchanged)" : ""}`);
  }
}
if (check && stale) {
  console.error(`\nthe docs editor bundle is out of date with server/docs-editor (source ${sourceHash}); run: npm run build:docs`);
  process.exit(1);
}
if (check) console.log(`docs editor bundle matches server/docs-editor (source ${sourceHash})`);
